import type { ReactNode } from 'react'
import { FloatingActionButton } from './FloatingActionButton'

interface ToolButton {
  key: string
  onClick: () => void
  icon: ReactNode
  className?: string
}

interface FloatingToolbarProps {
  buttons: ToolButton[]
  timelineOpen?: boolean
  extra?: ToolButton[]
}

export function FloatingToolbar({ buttons, timelineOpen, extra }: FloatingToolbarProps) {
  const rightClass = timelineOpen ? 'xl:right-[308px]' : ''

  const allButtons = [
    ...(extra ?? []),
    ...buttons,
  ]

  return (
    <div className={`fixed bottom-5 right-5 ${rightClass} z-30 flex flex-col items-center gap-3`}>
      {allButtons.map((btn) => (
        <FloatingActionButton
          key={btn.key}
          onClick={btn.onClick}
          className={(btn as any).className ?? 'p-3 bg-white dark:bg-gray-800'}
        >
          {btn.icon}
        </FloatingActionButton>
      ))}
    </div>
  )
}

