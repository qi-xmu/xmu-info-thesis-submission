import type { ReactNode } from 'react'
import { FloatingActionButton } from './FloatingActionButton'

interface ToolButton {
  key: string
  onClick: () => void
  icon: ReactNode
  className?: string
}

interface FloatingToolbarProps {
  buttons: ToolButton[]
  isDark: boolean
  onToggleDark: () => void
  timelineOpen?: boolean
  /** 额外自定义按钮 */
  extra?: ToolButton[]
}

export function FloatingToolbar({ buttons, isDark, onToggleDark, timelineOpen, extra }: FloatingToolbarProps) {
  const rightClass = timelineOpen ? 'xl:right-[308px]' : ''

  const allButtons = [
    ...(extra ?? []),
    ...buttons,
    {
      key: 'dark',
      onClick: onToggleDark,
      icon: isDark ? (
        <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 3v1m0 16v1m9-9h-1M4 12H3m15.364 6.364l-.707-.707M6.343 6.343l-.707-.707m12.728 0l-.707.707M6.343 17.657l-.707.707M16 12a4 4 0 11-8 0 4 4 0 018 0z" />
        </svg>
      ) : (
        <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M20.354 15.354A9 9 0 018.646 3.646 9.003 9.003 0 0012 21a9.003 9.003 0 008.354-5.646z" />
        </svg>
      ),
      className: 'p-3 bg-white dark:bg-gray-800',
    },
  ]

  return (
    <div className={`fixed bottom-5 right-5 ${rightClass} z-30 flex flex-col items-center gap-3`}>
      {allButtons.map((btn) => (
        <FloatingActionButton
          key={btn.key}
          onClick={btn.onClick}
          className={btn.className ?? 'p-3 bg-white dark:bg-gray-800'}
        >
          {btn.icon}
        </FloatingActionButton>
      ))}
    </div>
  )
}

